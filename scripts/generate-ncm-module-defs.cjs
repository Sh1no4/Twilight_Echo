// Generate `src/main/ncm/moduleDefs.generated.ts` — a build-time module registry
// for the NCM gateway.
//
// The NCM API server (`@neteasecloudmusicapienhanced/api/server.js`) loads its
// route handlers by `readdir(moduleDir)` then dynamically `require`s each file
// at startup. Those dynamic requires cannot be inlined by the sidecar bundler,
// and the route files `require('../util/…')` from their own directory, so a
// single-file bundle cannot run them. Instead we statically import every route
// module at build time and pass the resolved `moduleDefs` to `serveNcmApi`,
// which skips the runtime readdir/require entirely.
//
// The route mapping mirrors `server.js` `getModulesDefinitions`: special routes
// for `daily_signin` / `fm_trash` / `personal_fm`, otherwise
// `/${fileName.replace(/\.js$/i,'').replace(/_/g,'/')}`.
const { readdirSync, writeFileSync, statSync } = require('node:fs')
const { join } = require('node:path')

const MODULE_DIR = join(
  __dirname,
  '..',
  'node_modules/@neteasecloudmusicapienhanced/api/module'
)
const OUT = join(__dirname, '..', 'src/main/ncm/moduleDefs.generated.ts')

const SPECIAL = {
  daily_signin: '/daily_signin',
  fm_trash: '/fm_trash',
  personal_fm: '/personal_fm'
}

// Modules excluded from the build-time registry. `cloud.js` requires
// `music-metadata`, which is ESM-only and cannot be inlined into the single-file
// CJS sidecar bundle without shipping node_modules. Excluding the cloud-upload
// route keeps the gateway fully self-contained; all other NCM endpoints work.
const EXCLUDED = new Set(['cloud.js'])

const files = readdirSync(MODULE_DIR)
  .filter((f) => f.endsWith('.js') && statSync(join(MODULE_DIR, f)).isFile())
  .filter((f) => !EXCLUDED.has(f))
  .reverse() // mirror server.js `files.reverse()`

const lines = []
lines.push('// AUTO-GENERATED by scripts/generate-ncm-module-defs.cjs — do not edit.')
lines.push('// Inlines every NCM API route module so the gateway sidecar bundle is')
lines.push('// self-contained (no runtime readdir/dynamic require of module/*.js).')
lines.push('')
for (let i = 0; i < files.length; i++) {
  const fileName = files[i]
  lines.push(
    `import m${i} from '../../../node_modules/@neteasecloudmusicapienhanced/api/module/${fileName}'`
  )
}
lines.push('')
lines.push('export interface NcmModuleDef {')
lines.push('  identifier: string')
lines.push('  route: string')
lines.push('  module: (query: unknown, request: (...args: unknown[]) => unknown) => unknown')
lines.push('}')
lines.push('')
lines.push('export const NCM_MODULE_DEFS: NcmModuleDef[] = [')
for (let i = 0; i < files.length; i++) {
  const fileName = files[i]
  const identifier = fileName.split('.')[0]
  const route = SPECIAL[identifier] ?? `/${identifier.replace(/_/g, '/')}`
  lines.push(`  { identifier: ${JSON.stringify(identifier)}, route: ${JSON.stringify(route)}, module: m${i} },`)
}
lines.push(']')
lines.push('')

writeFileSync(OUT, lines.join('\n'))
process.stdout.write(`generated ${OUT} (${files.length} modules)\n`)
